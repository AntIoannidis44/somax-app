def diet_tags(base, p, c, kcal):
    d = list(base)
    if "vegan" in d:
        for x in ("vegetarian", "dairy-free"):
            if x not in d: d.append(x)
    if p >= 20 or (p >= 15 and 4 * p / kcal >= 0.30):
        d.append("high-protein")
    if c <= 15:
        d.append("low-carb")
    order = ["vegetarian", "vegan", "high-protein", "low-carb", "dairy-free", "gluten-free"]
    return [x for x in order if x in d]


