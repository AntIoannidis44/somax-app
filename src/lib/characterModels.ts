// Rest-pose pelvis position in the animation library's own rig, read from its file.
let animPelvisRest: THREE.Vector3 | null = null;

export function loadAnimationClips(): Promise<THREE.AnimationClip[]> {
  return loadGLTF(ANIMATIONS_URL).then((g) => {
    if (!animPelvisRest) {
      const node = (g.parser.json.nodes as { name?: string; translation?: number[] }[]).find((n) => n.name === 'pelvis');
      animPelvisRest = new THREE.Vector3().fromArray(node?.translation ?? [0, 0, 1]);
    }
    return g.animations;
  });
}

// The library's clips key translation (and scale) on all 65 bones, recorded on
// one fixed rig. Played raw, they overwrite each build's own bone lengths, so
// Teen got stretched to adult size and every build got that rig's proportions.
// Returns clips that keep rotations only, plus the pelvis motion rescaled to this
// character's own hip height. Call with the group composeCharacter returned.
const fittedClipCache = new WeakMap<THREE.AnimationClip, Map<string, THREE.AnimationClip>>();
export function fitClipsToCharacter(clips: THREE.AnimationClip[], group: THREE.Object3D): THREE.AnimationClip[] {
  const pelvisRest = group.userData.pelvisRest as THREE.Vector3 | undefined;
  if (!pelvisRest || !animPelvisRest) return clips;
  const anim = animPelvisRest;
  const k = pelvisRest.length() / anim.length();
  const cacheKey = pelvisRest.toArray().map((v) => v.toFixed(5)).join(',');
  return clips.map((clip) => {
    let perClip = fittedClipCache.get(clip);
    if (!perClip) fittedClipCache.set(clip, (perClip = new Map()));
    const hit = perClip.get(cacheKey);
    if (hit) return hit;
    const tracks: THREE.KeyframeTrack[] = [];
    for (const t of clip.tracks) {
      const [bone, prop] = t.name.split('.');
      if (prop === 'quaternion') tracks.push(t);
      else if (prop === 'position' && bone === 'pelvis') {
        const v = t.values.slice();
        for (let i = 0; i < v.length; i += 3) {
          v[i] = pelvisRest.x + (v[i] - anim.x) * k;
          v[i + 1] = pelvisRest.y + (v[i + 1] - anim.y) * k;
          v[i + 2] = pelvisRest.z + (v[i + 2] - anim.z) * k;
        }
        tracks.push(new THREE.VectorKeyframeTrack(t.name, t.times as unknown as number[], v as unknown as number[]));
      }
    }
    const fitted = new THREE.AnimationClip(clip.name, clip.duration, tracks);
    perClip.set(cacheKey, fitted);
    return fitted;
  });
}

function findSkinnedMeshes(root: THREE.Object3D): THREE.SkinnedMesh[] {
  const out: THREE.SkinnedMesh[] = [];
  root.traverse((o) => {
    if ((o as THREE.SkinnedMesh).isSkinnedMesh) out.push(o as THREE.SkinnedMesh);
  });
  return out;
}

// Rebuilds `mesh` (optionally with a replacement geometry) bound to the master
// skeleton's bones, matched by name, so it deforms in lockstep with the body.
// Outfits, heads and hair share the base bodies' rig family (identical joint
// names), and keep their own inverse bind matrices.
function attachToSkeleton(
  mesh: THREE.SkinnedMesh,
  boneByName: Map<string, THREE.Bone>,
  geometry: THREE.BufferGeometry = mesh.geometry,
): THREE.SkinnedMesh | null {
  const srcSkeleton = mesh.skeleton;
  const bones = srcSkeleton.bones.map((b) => boneByName.get(b.name));
  if (bones.some((b) => !b)) return null;
  const attached = new THREE.SkinnedMesh(geometry, mesh.material);
  attached.castShadow = false;
  attached.receiveShadow = false;
  const skeleton = new THREE.Skeleton(bones as THREE.Bone[], srcSkeleton.boneInverses);
  attached.bind(skeleton, mesh.bindMatrix);
  return attached;
}

// Fitting is pure geometry work, so it's done once per build and cached: one fit
// per gender+build, and one fitted geometry per source mesh per build.
const fitCache = new Map<string, Promise<OutfitFit>>();
const fittedGeometryCache = new Map<string, THREE.BufferGeometry>();
function getOutfitFit(build: BodyBuild, base: CharacterBase): Promise<OutfitFit> {
  const key = `${build}|${base}`;
  let p = fitCache.get(key);
  if (!p) {
    p = Promise.all([loadGLTF(BODY_URLS.regular[base]), loadGLTF(BODY_URLS[build][base])]).then(([r, t]) =>
      buildOutfitFit(r.scene, t.scene),
    );
    fitCache.set(key, p);
  }
  return p;
}
function fittedGeometry(fit: OutfitFit, mesh: THREE.SkinnedMesh, key: string): THREE.BufferGeometry {
  let g = fittedGeometryCache.get(key);
  if (!g) fittedGeometryCache.set(key, (g = fit.fitGeometry(mesh)));
  return g;
}

// Gym wear: garments are generated from the build's own body (see gymWear.ts), once per
// base+build+garment, and cached. With shoes on, the feet inside them aren't drawn.
const gymGeoCache = new Map<string, Promise<THREE.BufferGeometry | null>>();
const footlessCache = new Map<string, THREE.BufferGeometry>();
function gymGarment(srcSkin: THREE.SkinnedMesh, U: any, key: string, base: CharacterBase, build: BodyBuild, over?: any, overKey = '', patch?: object): Promise<THREE.BufferGeometry | null> {
  const ck = `${base}|${build}|${key}|${overKey}`;
  let job = gymGeoCache.get(ck);
  if (!job) {
    const onThisThread = () => {
      const spec = { ...(over || GARMENTS[key]), ...(patch || {}) };
      // per-build tweaks (e.g. Athletic only), exactly as approved in the Gym Wardrobe artifact
      const bspec = spec?.perBuild?.[build] ? { ...spec, ...spec.perBuild[build] } : spec;
      return buildGarment(bspec, srcSkin, joints(srcSkin));
    };
    job = isHeavyGarment(key) && !over ? buildInWorker(srcSkin, U, key, build, patch).catch((e) => { console.warn('gym worker unavailable, building on the main thread:', e); return onThisThread(); }) : Promise.resolve().then(onThisThread);
    gymGeoCache.set(ck, job);
  }
  return job;
}
// Headband vs hair (2026-11-20). The band is built on the bald head, so on most styles it would sit inside
// the hair. fitBandOverHair() pushes each part of the ring out to sit on top of THIS hairstyle (as a real
// headband sits over pulled-back hair). Only styles too voluminous for that keep the old approach of drawing
// the hair in front of the band (anything within 2cm), where the band shows only at the hairline.
// Checked from 5 angles for every style by tests/render/headband.mjs.
// Long loose hair falls over the band at the sides (only the forehead part shows), as in real life;
// long dreads are too voluminous to wrap. Every other style gets the band fitted over the hair.
const HAIR_OVER_BAND = new Set(['long', 'longDreads']);

// The hair model as it sits on THIS character's head, in the body mesh's own space (the hair keeps its own
// bind data; other builds move it onto their own head bones), so the band can be fitted against it.
const hairBodySpaceCache = new Map<string, THREE.BufferGeometry[]>();
function hairInBodySpace(hairMeshes: THREE.SkinnedMesh[], srcSkin: THREE.SkinnedMesh, key: string): THREE.BufferGeometry[] {
  const hit = hairBodySpaceCache.get(key);
  if (hit) return hit;
  const srcBind = new Map<string, THREE.Matrix4>();
  srcSkin.skeleton.bones.forEach((b, i) => srcBind.set(b.name, srcSkin.skeleton.boneInverses[i].clone().invert()));
  const toBody = srcSkin.bindMatrixInverse.clone();
  const out = hairMeshes.map((m) => {
    const g = m.geometry, pos = g.attributes.position, si = g.attributes.skinIndex, sw = g.attributes.skinWeight;
    const mats = m.skeleton.bones.map((b, j) => (srcBind.get(b.name) ?? new THREE.Matrix4()).clone().multiply(m.skeleton.boneInverses[j]));
    const P = new Float32Array(pos.count * 3), v = new THREE.Vector3(), acc = new THREE.Vector3(), t = new THREE.Vector3();
    for (let i = 0; i < pos.count; i++) {
      v.fromBufferAttribute(pos as THREE.BufferAttribute, i).applyMatrix4(m.bindMatrix);
      acc.set(0, 0, 0);
      for (let k = 0; k < 4; k++) {
        const w = sw.getComponent(i, k);
        if (w) acc.addScaledVector(t.copy(v).applyMatrix4(mats[si.getComponent(i, k)]), w);
      }
      acc.applyMatrix4(toBody);
      P[i * 3] = acc.x; P[i * 3 + 1] = acc.y; P[i * 3 + 2] = acc.z;
    }
    const h = new THREE.BufferGeometry();
    h.setAttribute('position', new THREE.BufferAttribute(P, 3));
    if (g.index) h.setIndex(g.index);
    return h;
  });
  hairBodySpaceCache.set(key, out);
  return out;
}

// Push each part of the headband ring outward just enough that hair can't poke through its outer surface
// (hair under the padded band is hidden anyway, so short styles barely move): around the head's centre line
// at the band's height, the outermost hair found within reach sets how far that part of the ring must move, and the result is smoothed into an even ring (no kinks). Parts with no
// hair under them (the forehead skin) don't move. Capped so a hanging tail or bun can't balloon the band.
const bandFitCache = new Map<string, THREE.BufferGeometry>();
function fitBandOverHair(band: THREE.BufferGeometry, hair: THREE.BufferGeometry[], key: string): THREE.BufferGeometry {
  const hit = bandFitCache.get(key);
  if (hit) return hit;
  const pos = band.attributes.position as THREE.BufferAttribute, n = pos.count;
  let cx = 0, cz = 0, ymin = Infinity, ymax = -Infinity;
  for (let i = 0; i < n; i++) { cx += pos.getX(i); cz += pos.getZ(i); ymin = Math.min(ymin, pos.getY(i)); ymax = Math.max(ymax, pos.getY(i)); }
  cx /= n; cz /= n;
  const BINS = 96, GAP = 0.0035, CAP = 0.03;
  const ang = (x: number, z: number) => ((Math.atan2(x - cx, z - cz) / (2 * Math.PI)) * BINS + BINS) % BINS;
  // outermost band radius (the surface hair must not poke through) and band height per bin
  const outer = new Array(BINS).fill(0), inner = new Array(BINS).fill(Infinity), ySum = new Array(BINS).fill(0), yN = new Array(BINS).fill(0);
  for (let i = 0; i < n; i++) {
    const b = Math.floor(ang(pos.getX(i), pos.getZ(i))) % BINS, r = Math.hypot(pos.getX(i) - cx, pos.getZ(i) - cz);
    inner[b] = Math.min(inner[b], r); outer[b] = Math.max(outer[b], r); ySum[b] += pos.getY(i); yN[b]++;
  }
  // Outermost hair surface per bin at band height, read straight from the hair's own points (each triangle's
  // corners + centre) - one pass over the data instead of ray-casting the whole model (that was ~300ms at
  // phone speed). Only hair within the band's height (plus a margin for its tilt) and within reach counts.
  const hairR = new Array(BINS).fill(0), PAD = (ymax - ymin) * 0.15;
  const V = [new THREE.Vector3(), new THREE.Vector3(), new THREE.Vector3(), new THREE.Vector3()];
  const take = (v: THREE.Vector3) => {
    if (v.y < ymin - PAD || v.y > ymax + PAD) return;
    const b = Math.floor(ang(v.x, v.z)) % BINS;
    if (!yN[b]) return;
    const r = Math.hypot(v.x - cx, v.z - cz);
    if (r <= outer[b] + CAP + GAP && r > hairR[b]) hairR[b] = r;
  };
  for (const g of hair) {
    const hp = g.attributes.position as THREE.BufferAttribute, ix = g.index ? g.index.array : null, tri = ix ? ix.length : hp.count;
    for (let t = 0; t + 2 < tri; t += 3) {
      for (let k = 0; k < 3; k++) V[k].fromBufferAttribute(hp, ix ? ix[t + k] : t + k);
      if (Math.max(V[0].y, V[1].y, V[2].y) < ymin - PAD || Math.min(V[0].y, V[1].y, V[2].y) > ymax + PAD) continue;
      V[3].copy(V[0]).add(V[1]).add(V[2]).multiplyScalar(1 / 3);
      for (const v of V) take(v);
    }
  }
  const need = hairR.map((h, b) => (yN[b] && h ? Math.min(CAP, Math.max(0, h + GAP - outer[b])) : 0));
  // even ring: spread each need over its neighbours (max, radius 3), then soften (mean, radius 3). The max
  // radius must be >= the mean radius so the softened ring never dips below what any part needs.
  const mx = need.map((_, b) => Math.max(...[-3, -2, -1, 0, 1, 2, 3].map((d) => need[(b + d + BINS) % BINS])));
  const push = mx.map((_, b) => [-3, -2, -1, 0, 1, 2, 3].reduce((s2, d) => s2 + mx[(b + d + BINS) % BINS], 0) / 7);
  const out = band.clone(), op = out.attributes.position as THREE.BufferAttribute;
  for (let i = 0; i < n; i++) {
    const x = op.getX(i) - cx, z = op.getZ(i) - cz, r = Math.hypot(x, z);
    if (r < 1e-6) continue;
    const f = ang(op.getX(i), op.getZ(i)), b0 = Math.floor(f) % BINS, t = f - Math.floor(f);
    const d = push[b0] * (1 - t) + push[(b0 + 1) % BINS] * t;
    op.setXYZ(i, cx + (x / r) * (r + d), op.getY(i), cz + (z / r) * (r + d));
  }
  op.needsUpdate = true;
  out.computeBoundingSphere();
  bandFitCache.set(key, out);
  return out;
}
function drawHairOverBand(mat: THREE.Material) {
  mat.onBeforeCompile = (sh) => {
    sh.vertexShader = sh.vertexShader.replace('#include <project_vertex>', `#include <project_vertex>
      { vec4 nearer = projectionMatrix * vec4(mvPosition.xy, mvPosition.z + 0.02, 1.0); gl_Position.z = nearer.z / nearer.w * gl_Position.w; }`);
  };
  mat.customProgramCacheKey = () => 'hair-over-band';
}
// The body with what's covered taken away: the feet inside shoes, and whatever each garment hides
// (a triangle goes when all three corners are hidden), so skin can't poke through the clothes.
const bodyCutCache = new Map<string, THREE.BufferGeometry>();
function coveredBody(srcSkin: THREE.SkinnedMesh, cfg: CharacterConfig, hides: { key: string; hide: any }[], shoes: boolean): THREE.BufferGeometry {
  const start = shoes ? footless(srcSkin, cfg.base, cfg.build) : srcSkin.geometry;
  if (!hides.length) return start;
  const ck = `${cfg.base}|${cfg.build}|${shoes}|${hides.map((h) => h.key).join(',')}`;
  let g = bodyCutCache.get(ck);
  if (!g) {
    const pos = start.attributes.position, idx = start.index!.array, V = new THREE.Vector3(), keep: number[] = [];
    const inR = (i: number) => { V.fromBufferAttribute(pos as THREE.BufferAttribute, i); return hides.some(({ hide: r }) => (r.mask ? r.mask[i] === 1 : r.fn ? r.fn(V) : V.y > r.y0 && V.y < r.y1)); };
    for (let t = 0; t < idx.length; t += 3) if (!(inR(idx[t]) && inR(idx[t + 1]) && inR(idx[t + 2]))) keep.push(idx[t], idx[t + 1], idx[t + 2]);
    g = start.clone();
    g.setIndex(keep);
    bodyCutCache.set(ck, g);
  }
  return g;
}
function footless(srcSkin: THREE.SkinnedMesh, base: CharacterBase, build: BodyBuild): THREE.BufferGeometry {
  const ck = `${base}|${build}`;
  let g = footlessCache.get(ck);
  if (!g) {
    const J = joints(srcSkin), full = srcSkin.geometry, pos = full.attributes.position, idx = full.index!.array;
    const cut = J.foot.y + GARMENTS.trainers.collar - 0.012, keep: number[] = [];
    for (let t = 0; t < idx.length; t += 3) {
      if (!(pos.getY(idx[t]) < cut && pos.getY(idx[t + 1]) < cut && pos.getY(idx[t + 2]) < cut)) keep.push(idx[t], idx[t + 1], idx[t + 2]);
    }
    g = full.clone();
    g.setIndex(keep);
    footlessCache.set(ck, g);
  }
  return g;
}

